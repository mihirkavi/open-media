function start(label: string, command: string, args: string[], cwd: string, extraEnv: Record<string, string> = {}) {
  const child = spawn(command, args, { cwd, env: { ...childEnv, ...extraEnv }, stdio: ['ignore', 'pipe', 'pipe'] });
  const prefix = `[${label}] `;
  const relay = (chunk: Buffer) => process.stdout.write(chunk.toString().split('\n').filter(Boolean).map((line) => prefix + line).join('\n') + '\n');
  child.stdout?.on('data', relay);
  child.stderr?.on('data', relay);
  child.on('exit', (code) => {
    if (!shuttingDown) {
      console.error(`\n✗ ${label} stopped (exit ${code}). Stopping Open Media.`);
      stopChildren();
      process.exit(code ?? 1);
    }
  });
  children.push(child);
}

let shuttingDown = false;
function stopChildren() {
  shuttingDown = true;
  for (const child of children) if (!child.killed) child.kill('SIGINT');
}
process.on('SIGINT', () => { console.log('\nStopping Open Media (Supabase keeps running; `npm run local:stop` stops it)…'); stopChildren(); setTimeout(() => process.exit(0), 1500); });
process.on('SIGTERM', () => { stopChildren(); process.exit(0); });

async function waitFor(url: string, label: string, seconds = 90) {
  for (let elapsed = 0; elapsed < seconds; elapsed += 2) {
    try { if ((await fetch(url)).status < 500) return; } catch { /* not ready yet */ }
    await sleep(2000);
  }
  throw new Error(`The ${label} did not start within ${seconds} seconds. See the log above.`);
}

function readSmtpEnv(): { enabled: boolean; host: string } {
  const file = join(root, 'supabase', '.env');
  if (!existsSync(file)) return { enabled: false, host: '' };
  const values = Object.fromEntries(readFileSync(file, 'utf8').split('\n').map((line) => line.split('=')).filter((parts) => parts.length >= 2).map(([key, ...rest]) => [key.trim(), rest.join('=').trim()]));
  return { enabled: values.OPEN_MEDIA_SMTP_ENABLED === 'true', host: values.OPEN_MEDIA_SMTP_HOST ?? '' };
}

