/**
 * `npm run app:install` — installs "Open Media.app" in ~/Applications so it can
 * live in the Dock. Opening it starts the local stack (`npm run local`) in the
 * background if it is not already running, waits until it is ready, and opens
 * Open Media in its own window (Chrome app window when available, else Safari).
 *
 * The app is a small launcher; the code stays in this repository. Logs go to
 * .local/logs/ inside the repository. `npm run app:uninstall` removes it.
 */
import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appPath = join(homedir(), 'Applications', 'Open Media.app');

if (process.argv.includes('--uninstall')) {
  rmSync(appPath, { recursive: true, force: true });
  console.log(`✓ Removed ${appPath}`);
  process.exit(0);
}

const contents = join(appPath, 'Contents');
rmSync(appPath, { recursive: true, force: true });
mkdirSync(join(contents, 'MacOS'), { recursive: true });
mkdirSync(join(contents, 'Resources'), { recursive: true });

writeFileSync(join(contents, 'Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Open Media</string>
  <key>CFBundleDisplayName</key><string>Open Media</string>
  <key>CFBundleIdentifier</key><string>local.openmedia.launcher</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>Open Media</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>LSUIElement</key><false/>
</dict>
</plist>
`);

const launcher = `#!/bin/bash
# Open Media launcher (generated by npm run app:install). Starts the local stack if needed, then opens the app.
REPO=${shellQuote(root)}
URL="http://localhost:8081"
LOGS="$REPO/.local/logs"
mkdir -p "$LOGS"
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
NODE="$(ls -d "$HOME"/.nvm/versions/node/v2[2-9]*/bin 2>/dev/null | sort -V | tail -1)"
[ -n "$NODE" ] && export PATH="$NODE:$PATH"

notify() { osascript -e "display notification \\"$1\\" with title \\"Open Media\\"" >/dev/null 2>&1; }

ready() { curl -s -m 2 -o /dev/null "$URL" && curl -s -m 2 -o /dev/null http://127.0.0.1:8787/health; }

if ! ready; then
  notify "Starting Open Media… this takes up to a minute the first time."
  if [ ! -f "$REPO/.local/local.pid" ] || ! kill -0 "$(cat "$REPO/.local/local.pid")" 2>/dev/null; then
    cd "$REPO" && OPEN_MEDIA_NO_BROWSER=1 nohup npm run local >"$LOGS/local.log" 2>&1 &
    echo $! > "$REPO/.local/local.pid"
  fi
  for _ in $(seq 1 120); do ready && break; sleep 2; done
  if ! ready; then
    osascript -e 'display alert "Open Media could not start" message "See .local/logs/local.log in the project folder. Docker Desktop must be installed."' >/dev/null 2>&1
    exit 1
  fi
fi

# OPEN_MEDIA_NO_WINDOW=1 starts the stack without opening a window (for testing).
if [ -n "$OPEN_MEDIA_NO_WINDOW" ]; then exit 0; fi
if [ -d "/Applications/Google Chrome.app" ]; then
  open -na "Google Chrome" --args --app="$URL" --new-window
else
  open -a Safari "$URL"
fi
exit 0
`;
const executable = join(contents, 'MacOS', 'Open Media');
writeFileSync(executable, launcher);
chmodSync(executable, 0o755);

// App icon from the project's icon, in all the sizes macOS expects.
const iconSource = join(root, 'assets', 'icon.png');
if (existsSync(iconSource)) {
  const iconset = join(root, '.local', 'AppIcon.iconset');
  rmSync(iconset, { recursive: true, force: true });
  mkdirSync(iconset, { recursive: true });
  for (const size of [16, 32, 128, 256, 512]) {
    for (const scale of [1, 2]) {
      const pixels = size * scale;
      const name = `icon_${size}x${size}${scale === 2 ? '@2x' : ''}.png`;
      execFileSync('sips', ['-z', String(pixels), String(pixels), iconSource, '--out', join(iconset, name)], { stdio: 'ignore' });
    }
  }
  execFileSync('iconutil', ['-c', 'icns', iconset, '-o', join(contents, 'Resources', 'AppIcon.icns')]);
  rmSync(iconset, { recursive: true, force: true });
}

// Refresh Finder/Dock icon caches for the new bundle.
execFileSync('touch', [appPath]);
console.log(`✓ Installed ${appPath}
  Open it from Finder → Applications (your user Applications folder), then right-click its Dock icon → Options → Keep in Dock.
  It starts the local stack when needed and opens Open Media in its own window.`);

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
