/**
 * `npm run app:install` — installs "Open Media.app" in ~/Applications so it can
 * live in the Dock, plus a LaunchAgent (local.openmedia.stack) that runs the local
 * stack (`scripts/local.ts --app`) in the background.
 *
 * Opening the app shows Open Media in its own window (Chrome app window when available,
 * else Safari) straight away. When the stack isn't running, the launcher starts the
 * LaunchAgent, and the window shows a "Starting…" page with each step until the app is
 * ready. The stack keeps running after the window closes, so the next open is instant.
 * It runs under launchd rather than as a child of the app, because macOS ends an app's
 * child processes when the app's own process exits.
 *
 * The app is a small launcher; the code stays in this repository. The log is
 * .local/logs/local.log. `npm run app:stop` stops the background stack (the database keeps
 * running; `npm run local:stop` stops it). `npm run app:uninstall` removes both.
 */
import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appPath = join(homedir(), 'Applications', 'Open Media.app');
const agentLabel = 'local.openmedia.stack';
const agentPath = join(homedir(), 'Library', 'LaunchAgents', `${agentLabel}.plist`);
const domain = `gui/${process.getuid?.()}`;

/** Stops the background stack and unloads the LaunchAgent. Fine when neither is running. */
function unloadAgent() {
  try { execFileSync('launchctl', ['bootout', `${domain}/${agentLabel}`], { stdio: 'ignore' }); } catch { /* not loaded */ }
}

if (process.argv.includes('--stop')) {
  try { execFileSync('launchctl', ['kill', 'SIGTERM', `${domain}/${agentLabel}`], { stdio: 'ignore' }); } catch { /* not running */ }
  console.log('✓ Stopped the Open Media background stack. `npm run local:stop` also stops the database.');
  process.exit(0);
}

if (process.argv.includes('--uninstall')) {
  unloadAgent();
  rmSync(agentPath, { force: true });
  rmSync(appPath, { recursive: true, force: true });
  console.log(`✓ Removed ${appPath} and its background agent`);
  process.exit(0);
}

const contents = join(appPath, 'Contents');
rmSync(appPath, { recursive: true, force: true });
mkdirSync(join(contents, 'MacOS'), { recursive: true });
mkdirSync(join(contents, 'Resources'), { recursive: true });

writeFileSync(join(contents, 'Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Open Media</string>
  <key>CFBundleDisplayName</key><string>Open Media</string>
  <key>CFBundleIdentifier</key><string>local.openmedia.launcher</string>
  <key>CFBundleVersion</key><string>2</string>
  <key>CFBundleShortVersionString</key><string>2.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>Open Media</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>LSUIElement</key><false/>
</dict>
</plist>
`);

const launcher = `#!/bin/bash
# Open Media launcher (generated by npm run app:install).
# Opens the app window at once; starts the background stack (LaunchAgent ${agentLabel}) when it isn't running.
REPO=${shellQuote(root)}
URL="http://localhost:8081"
AGENT="gui/$(id -u)/${agentLabel}"
PLIST="$HOME/Library/LaunchAgents/${agentLabel}.plist"
LOG="$REPO/.local/logs/local.log"

# --stack: what the LaunchAgent runs. Finds Node.js 22+ and runs the stack in app mode.
if [ "$1" = "--stack" ]; then
  export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
  NODE="$(ls -d "$HOME"/.nvm/versions/node/v2[2-9]*/bin 2>/dev/null | sort -V | tail -1)"
  [ -n "$NODE" ] && export PATH="$NODE:$PATH"
  mkdir -p "$REPO/.local/logs"
  exec >"$LOG" 2>&1
  cd "$REPO" || exit 1
  command -v node >/dev/null || { echo "✗ Node.js 22 or newer was not found (looked in ~/.nvm)."; exit 1; }
  exec node --import tsx scripts/local.ts --app
fi

fail() {
  local detail
  detail="$(grep -E '✗|[Ee]rror' "$LOG" 2>/dev/null | tail -3 | perl -pe 's/\\e\\[[0-9;]*m//g' | tr '"\\\\' "'/" | cut -c1-300)"
  osascript -e "display alert \\"Open Media could not start\\" message \\"$1\\n\\n\${detail:-No error in the log.}\\n\\nFull log: .local/logs/local.log in the project folder.\\"" >/dev/null 2>&1
  exit 1
}

up() { curl -s -m 1 -o /dev/null "$URL/"; }

if ! up; then
  launchctl print "$AGENT" >/dev/null 2>&1 || launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null
  launchctl kickstart "$AGENT" >/dev/null 2>&1 || fail "The background agent could not start. Run npm run app:install in the project folder."
  # The stack answers with its "Starting…" page within a second or two.
  for _ in $(seq 1 100); do up && break; sleep 0.15; done
  up || fail "The background stack did not start."
fi

# OPEN_MEDIA_NO_WINDOW=1 starts the stack without opening a window (for testing).
if [ -n "$OPEN_MEDIA_NO_WINDOW" ]; then exit 0; fi
if [ -d "/Applications/Google Chrome.app" ]; then
  open -na "Google Chrome" --args --app="$URL" --new-window
else
  open -a Safari "$URL"
fi
exit 0
`;
const executable = join(contents, 'MacOS', 'Open Media');
writeFileSync(executable, launcher);
chmodSync(executable, 0o755);

// The LaunchAgent that runs the stack. It starts only when the launcher asks (no RunAtLoad), and
// runs as an interactive process so macOS doesn't throttle it as background work.
mkdirSync(dirname(agentPath), { recursive: true });
writeFileSync(agentPath, `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${agentLabel}</string>
  <key>ProgramArguments</key>
  <array><string>${xmlEscape(executable)}</string><string>--stack</string></array>
  <key>RunAtLoad</key><false/>
  <key>KeepAlive</key><false/>
  <key>ProcessType</key><string>Interactive</string>
</dict>
</plist>
`);
unloadAgent();
execFileSync('launchctl', ['bootstrap', domain, agentPath]);

// App icon from the project's icon, in all the sizes macOS expects.
const iconSource = join(root, 'assets', 'icon.png');
if (existsSync(iconSource)) {
  const iconset = join(root, '.local', 'AppIcon.iconset');
  rmSync(iconset, { recursive: true, force: true });
  mkdirSync(iconset, { recursive: true });
  for (const size of [16, 32, 128, 256, 512]) {
    for (const scale of [1, 2]) {
      const pixels = size * scale;
      const name = `icon_${size}x${size}${scale === 2 ? '@2x' : ''}.png`;
      execFileSync('sips', ['-z', String(pixels), String(pixels), iconSource, '--out', join(iconset, name)], { stdio: 'ignore' });
    }
  }
  execFileSync('iconutil', ['-c', 'icns', iconset, '-o', join(contents, 'Resources', 'AppIcon.icns')]);
  rmSync(iconset, { recursive: true, force: true });
}

// Refresh Finder/Dock icon caches for the new bundle.
execFileSync('touch', [appPath]);
console.log(`✓ Installed ${appPath}
  Open it from Finder → Applications (your user Applications folder), then right-click its Dock icon → Options → Keep in Dock.
  It opens Open Media in its own window at once and starts the local stack in the background when needed.
  \`npm run app:stop\` stops the background stack.`);

function xmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
