/**
 * `npm run bridges` — sets up and starts Open Media's bridged messaging stack
 * (ADR 0011) on this computer: a private Synapse homeserver plus the
 * mautrix-whatsapp bridge, from services/bridges/docker-compose.yml.
 * `npm run bridges:stop` stops it.
 *
 * Everything generated stays in .local/bridges (gitignored): homeserver and
 * bridge configuration, their databases, and the secrets the mail service
 * uses to reach them (.local/bridges/worker.env, read by `npm run local`).
 *
 * Open Media users appear on the homeserver as @om_<id>. They are created and
 * acted for by Open Media's own application service, so no Matrix passwords
 * or per-user tokens exist; the mail service maps each signed-in person to
 * exactly one Matrix user.
 */
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const compose = join(root, 'services', 'bridges', 'docker-compose.yml');
const base = join(root, '.local', 'bridges');
const synapseDir = join(base, 'synapse');
const whatsappDir = join(base, 'whatsapp');
const serverName = 'openmedia.localhost';
const synapseImage = 'matrixdotorg/synapse:v1.163.1';
const whatsappImage = 'dock.mau.dev/mautrix/whatsapp:v0.2610.0';

if (process.argv[2] === 'stop') {
  docker(['compose', '-f', compose, 'down']);
  console.log('✓ Bridges stopped. Data stays in .local/bridges.');
  process.exit(0);
}

mkdirSync(synapseDir, { recursive: true });
mkdirSync(whatsappDir, { recursive: true });
writeFileSync(join(base, 'README.md'), '# .local/bridges\n\nGenerated by `npm run bridges` (gitignored): Synapse and bridge configuration, databases, and secrets for local development. Deleting it disconnects every bridged account.\n');

const secrets = loadSecrets();

step('Configuring the homeserver');
if (!existsSync(join(synapseDir, 'homeserver.yaml'))) {
  docker(['run', '--rm', '-v', `${synapseDir}:/data`, '-e', `SYNAPSE_SERVER_NAME=${serverName}`, '-e', 'SYNAPSE_REPORT_STATS=no', synapseImage, 'generate']);
}
writeFileSync(join(synapseDir, 'openmedia-registration.yaml'), YAML.stringify({
  id: 'openmedia',
  url: null,
  as_token: secrets.asToken,
  hs_token: secrets.hsToken,
  sender_localpart: 'openmedia-gateway',
  rate_limited: false,
  namespaces: { users: [{ regex: `@om_[a-f0-9]{32}:${serverName.replace(/\./g, '\\.')}`, exclusive: true }], aliases: [], rooms: [] },
}));

step('Configuring the WhatsApp bridge');
const whatsappConfig = join(whatsappDir, 'config.yaml');
if (!existsSync(whatsappConfig)) docker(['run', '--rm', '-v', `${whatsappDir}:/data`, whatsappImage]);
const config = YAML.parseDocument(readFileSync(whatsappConfig, 'utf8'));
config.setIn(['homeserver', 'address'], 'http://synapse:8008');
config.setIn(['homeserver', 'domain'], serverName);
config.setIn(['appservice', 'address'], 'http://whatsapp:29318');
config.setIn(['appservice', 'hostname'], '0.0.0.0');
config.setIn(['database', 'type'], 'sqlite3-fk-wal');
config.setIn(['database', 'uri'], 'file:/data/whatsapp.db?_txlock=immediate');
// Only Open Media's own users may log in; nobody else can use this bridge.
config.setIn(['bridge', 'permissions'], { [serverName]: 'user' });
config.setIn(['provisioning', 'shared_secret'], secrets.provisioning);
// The bridge acts as each person through Open Media's appservice, so new chats join automatically.
config.setIn(['double_puppet', 'secrets'], { [serverName]: `as_token:${secrets.asToken}` });
config.setIn(['backfill', 'enabled'], true);
config.setIn(['bridge', 'cleanup_on_logout', 'enabled'], true);
writeFileSync(whatsappConfig, String(config));
const registration = join(whatsappDir, 'registration.yaml');
docker(['run', '--rm', '-v', `${whatsappDir}:/data`, whatsappImage]);
if (!existsSync(registration)) throw new Error('The WhatsApp bridge did not write registration.yaml.');
copyFileSync(registration, join(synapseDir, 'whatsapp-registration.yaml'));

const homeserver = YAML.parseDocument(readFileSync(join(synapseDir, 'homeserver.yaml'), 'utf8'));
homeserver.set('app_service_config_files', ['/data/openmedia-registration.yaml', '/data/whatsapp-registration.yaml']);
homeserver.set('enable_registration', false);
writeFileSync(join(synapseDir, 'homeserver.yaml'), String(homeserver));

writeFileSync(join(base, 'worker.env'), [
  '# Generated by `npm run bridges`. Local development only.',
  'BRIDGES_HOMESERVER_URL=http://127.0.0.1:8008',
  `BRIDGES_SERVER_NAME=${serverName}`,
  `BRIDGES_AS_TOKEN=${secrets.asToken}`,
  `BRIDGES_PROVISIONING_SECRET=${secrets.provisioning}`,
  'BRIDGES_WHATSAPP_URL=http://127.0.0.1:29318',
  '',
].join('\n'), { mode: 0o600 });

step('Starting Synapse and the WhatsApp bridge');
docker(['compose', '-f', compose, 'up', '-d', '--force-recreate']);
console.log(`
✓ Bridges are running (homeserver http://127.0.0.1:8008, WhatsApp bridge http://127.0.0.1:29318).
  Restart \`npm run local\` so the mail service picks up .local/bridges/worker.env.
  \`npm run bridges:stop\` stops them.
`);

function loadSecrets(): { asToken: string; hsToken: string; provisioning: string } {
  const file = join(base, 'secrets.json');
  if (existsSync(file)) return JSON.parse(readFileSync(file, 'utf8'));
  const created = { asToken: token(), hsToken: token(), provisioning: token() };
  writeFileSync(file, JSON.stringify(created, null, 2), { mode: 0o600 });
  return created;
}

function token(): string {
  return randomBytes(32).toString('base64url');
}

function docker(args: string[]) {
  execFileSync('docker', args, { stdio: 'inherit', cwd: root });
}

function step(message: string) {
  console.log(`→ ${message}`);
}
